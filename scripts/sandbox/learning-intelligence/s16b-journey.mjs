/** S1.6B: same-learner chronological synthetic-memory journey; model calls are explicit opt-in. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {flags as baseFlags, runSimulation, writeReport} from './s16-space-sim.mjs';
const HERE=path.dirname(fileURLToPath(import.meta.url));
const ROOT=path.resolve(HERE,'../../../');
const PLAN=['T01','T07','T10','T02','T06','T08','T15','T11'];
const EXPECTED_SEED_HASH='85b4bcd6208a6b8e4ac320725fd2c040e6087491b44953e8d6e2820e7b6235b4';
const S16A_HASH='9ee7e829d9bcd28c2d898873e047b76071ffe152769b439fb6c4983c3045d2e5';
const digest=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const str=x=>String(x??'');
const trim=x=>str(x).replace(/[\x00-\x08\x0b\x0c\x0e-\x1f]/g,'').slice(0,3000);
export function parseJourneyArgs(argv){
 const conf=baseFlags(argv);
 if(!argv.includes('--limit'))conf.limit=conf.mode==='model'?3:PLAN.length;
 if(conf.limit>PLAN.length)throw Error('S1.6B journey has only '+PLAN.length+' chronological turns');
 // Model calls remain bounded by S1.6A to a maximum six turns and explicit opt-in.
 return conf;
}
export function loadJourneySeed(){
 const location=path.join(HERE,'s16-seed.json');
 if(digest(location)!==EXPECTED_SEED_HASH)throw Error('S1.6A seed changed; refuse an unreviewed longitudinal scenario');
 const seed=JSON.parse(fs.readFileSync(location,'utf8'));
 if(seed.schema!=='myway-s16-synthetic-space-v1'||seed.topics.length!==12)throw Error('Unexpected S1.6A seed contract');
 const byId=new Map(seed.turns.map(x=>[x.turn_id,x]));
 const turns=PLAN.map(id=>{const x=byId.get(id);if(!x)throw Error('Missing expected scenario turn '+id);return structuredClone(x);});
 return {...seed,notice:seed.notice+' Same learner across repeated visits; historical state evolves. Prewritten responses are not generated by the teacher.',turns};
}
function own(o,k){return Object.prototype.hasOwnProperty.call(o,k);}
export function analyzeJourney(result){
 if(!result||!Array.isArray(result.turns)||!result.finalState?.topics)throw Error('Invalid S1.6A trace');
 const evaluated=[];
 for(const turn of result.turns){
  const expect=turn.referenceForEvaluationOnly??{};
  const decision=turn.modelC?.identity??null;
  const topicMatched=turn.retrieval?.topicId===expect.topic_id;
  const hold=/hold|clarif|not_started|stopped_on_error/.test(turn.action?.kind??'');
  const identityComparable=['same','distinct'].includes(decision)&&['same','distinct'].includes(expect.identity);
  const topicRanking=turn.retrieval?.topicCandidates??[];
  const selected=topicRanking.find(x=>x.topicId===turn.retrieval?.topicId);
  const outside=topicRanking.filter(x=>x.topicId!==turn.retrieval?.topicId && typeof x.bestEventSimilarity==='number' && x.bestEventSimilarity>=0.42)
   .slice(0,3).map(x=>({topicId:x.topicId,label:x.topicLabel,similarity:x.bestEventSimilarity,selectedBest:selected?.bestEventSimilarity??null,reason:'Similar historical roots across topics; NOT proof of a conceptual relationship'}));
  evaluated.push({turnId:turn.turnId,expectedTopicId:expect.topic_id??null,expectedIdentity:expect.identity??null,topicMatched:turn.retrieval?topicMatched:null,modelCIdentity:decision,decided:identityComparable,identityMatched:identityComparable?decision===expect.identity:null,held:hold,
   teacherIsReal:result.mode==='model'&&Boolean(turn.teaching),teacherFlags:turn.teacherStyle??null,
   embeddedCrossTopicCandidates:outside,action:turn.action?.kind??'unknown',
   originFlags:{assessment:turn.assessmentOrigin??null,teaching:turn.teaching?.source??(result.mode==='model'?'REAL_PROVIDER_IF_PRESENT':'NOT_REAL'),memory:turn.modelC?.source??(result.mode==='model'?'REAL_PROVIDER_IF_PRESENT':'NOT_REAL')},
   importantCaveat:'Expected labels are synthetic test references, not independent expert annotations.'});
 }
 const judged=evaluated.filter(x=>x.decided);
 const counted=result.turns.filter(t=>t.error).length;
 const repairEvidence=result.corrections.map(x=>({priorEventId:x.prior_event_id,triggerTurn:x.current_turn_id,status:x.status,automaticRepairApplied:!!x.automatic_repair_applied,evidence:x.evidence_quote,note:'Candidate only; no independent confirmation or autonomous relink.'}));
 const faultEvents=result.audit.filter(x=>x.kind==='EXPLICIT_SYNTHETIC_FAULT_INJECTION');
 const oracleRepairControls=faultEvents.map(x=>{
   const eventId=result.turns.find(t=>t.turnId===x.change.turn_id)?.action?.newEventId;
   const event=result.finalState.topics.flatMap(t=>t.events).find(e=>e.event_id===eventId);
   const alarm=result.corrections.find(c=>c.prior_event_id===eventId);
   return {eventId,originTurn:x.change.turn_id,alarmDetected:Boolean(alarm),currentDifficultyId:event?.difficulty_id??null,
     knownOriginalDifficultyId:x.change.original_difficulty_id,wrongDifficultyId:x.change.wrong_difficulty_id,
     oracleRestorationPlan:alarm&&event?.difficulty_id===x.change.wrong_difficulty_id?{operation:'relink_event',eventId,from:x.change.wrong_difficulty_id,to:x.change.original_difficulty_id,reversible:true,applied:false}:null,
     warning:'This plan uses fault-injection oracle provenance; it is NOT discovered by the models and is never applied.'};
 });
 return {schema:'myway-s16b-review-v1',scenario:'one synthetic learner across chronological visits',mode:result.mode,turns:evaluated,
  summary:{processed:result.turns.length,modelCalls:result.cost?.attemptedCalls??0,teacherResponsesFromModel:evaluated.filter(x=>x.teacherIsReal).length,held:evaluated.filter(x=>x.held).length,
   identityDecisionsWithSyntheticReference:judged.length,identityMatchesOnDecided:judged.filter(x=>x.identityMatched).length,
   topicMatchesOnRetrieved:evaluated.filter(x=>x.topicMatched===true).length,topicMismatchesOnRetrieved:evaluated.filter(x=>x.topicMatched===false).length,
   relationshipHypotheses:result.relationships.length,repairCandidates:result.corrections.length,sourceErrors:counted,
   injectedFaultControls:faultEvents.length,automaticCorrectionsApplied:repairEvidence.filter(x=>x.automaticRepairApplied).length},
  repairEvidence,oracleRepairControls,semanticRivalWatchlist:evaluated.flatMap(x=>x.embeddedCrossTopicCandidates.map(y=>({turnId:x.turnId,...y}))),
  relationships:result.relationships.map(x=>({...x,verification:'unverified',relationshipScope:'topic-pair hypothesis; NOT a verified concept/difficulty-level edge',evidenceOrigin:'explicit learner comparison, not autonomous semantic discovery'})),
  limitations:['No production database access or writes','Seeded follow-up messages are authored, not generated in response to Model B','Model A does not receive the entire transcript; it assesses each statement as a new message','Topic selection relies on the experimental whole-bank retrieval; real Supabase owner-scoped retrieval not tested','Unknown/held Model C decisions remain holds, not new difficulty creation','Relationship proposals are not independently verified','Correction proposals do not automatically move or rewrite historical evidence','Synthetic expected labels are not independent expert ground truth','Provider budget is admission control, not a hard billing cap']};
}
export function formatReview(result,review){
 const lines=[];const out=(...a)=>lines.push(...a);
 out('MYWAY S1.6B — LONGITUDINAL LEARNING SPACE REVIEW','='.repeat(85),
  'Same synthetic learner, repeated visits to a stateful local memory. No Supabase writes.',
  `MODE: ${result.mode} | completed ${result.turns.length} turns | known cost est USD ${result.cost?.knownEstimatedUsd??0}`,
  result.mode==='model'?'Real GPT model outputs where calls succeeded; do not assume educational correctness.':'OFFLINE ONLY: Model A, B and C outcomes are scripted/heuristic. Not a model evaluation.',
  'REFERENCE EXPECTATIONS ARE SYNTHETIC and were not provided to inference models.','');
 out('===== SUMMARY =====',JSON.stringify(review.summary,null,2),'');
 for(let i=0;i<result.turns.length;i++){
  const t=result.turns[i],e=review.turns[i];
  out(`===== VISIT ${i+1}: ${t.turnId} =====`,'LEARNER SAYS:',trim(t.message),'',
   'MODEL A — ASSESSMENT:',`  origin: ${trim(t.assessmentOrigin)}`,`  topic: ${trim(t.assessment?.topic_name)}`,`  root problem: ${trim(t.assessment?.root_problem)}`,`  quote: ${trim(t.assessment?.evidence_quote)}`,`  gate: ${trim(t.gate?.route)}`,`  clarification question: ${trim(t.gate?.question??'(none)')}`,'',
   'MODEL B — LEARNER-FACING TEACHING:',trim(t.teaching?.teaching_strategy??'(not produced)'),`NEXT STEP: ${trim(t.teaching?.next_step??'(none)')}`,`VISUAL: ${trim(t.teaching?.visual_intent??'none')}`,
   `MECHANICAL STYLE FLAGS ONLY: ${JSON.stringify(t.teacherStyle??{})}`,
   'TEACHER HUMAN-REVIEW RUBRIC (not automatically scored):',
   '  1. Is the mechanism/explanation factually accurate?       [review]',
   '  2. Does it address the actual confusion without conflation? [review]',
   '  3. Does it sound like MyWay—direct, natural, supportive?   [review]',
   '  4. Is the next step useful and non-repetitive?              [review]',
   '  5. Is the visual helpful rather than decorative?           [review]','',
   'MEMORY RETRIEVAL:',`  chosen topic: ${trim(t.retrieval?.topicLabel)}`,`  integrity: ${JSON.stringify(t.integrity)}`,`  top three: ${JSON.stringify(t.retrieval?.topicCandidates?.slice(0,3)??[])}`,'',
   'MODEL C / SIMULATED MEMORY ACTION:',`  identity: ${trim(t.modelC?.identity??'not run')}`,`  interpretation: ${trim(t.modelC?.interpretation??'-')}`,`  anchor: ${trim(t.modelC?.anchor_event_id??'-')}`,`  action: ${JSON.stringify(t.action)}`,
   `  synthetic reference: ${JSON.stringify(t.referenceForEvaluationOnly??{})}`,
   `  matching reference: topic=${e.topicMatched}, identity=${e.identityMatched}`,
   `  status note: ${e.importantCaveat}`,'',
   'RELATIONSHIPS / CORRECTION OBSERVATIONS:',`  explicit relationship hypotheses: ${JSON.stringify(t.relations??[])}`,
   `  cross-topic semantic rivals, NOT relationships: ${JSON.stringify(e.embeddedCrossTopicCandidates)}`,
   `  correction candidates: ${JSON.stringify(t.corrections??[])}`,'');
  if(t.faultInjection)out('  EXPLICIT TEST-ONLY INJECTED MEMORY ERROR: '+JSON.stringify(t.faultInjection),'');
  if(t.error)out('  ERROR (STOP): '+trim(t.error),'');
 }
 out('===== RELATIONSHIPS: EVIDENCE / LIMITATIONS =====');
 for(const r of review.relationships)out(JSON.stringify(r));
 if(!review.relationships.length)out('(None. This does NOT imply none exist.)');
 out('','===== SEMANTIC CROSS-TOPIC RIVALS (NOT RELATIONSHIP DISCOVERIES) =====');
 for(const c of review.semanticRivalWatchlist)out(JSON.stringify(c));
 if(!review.semanticRivalWatchlist.length)out('(None above provisional research floor.)');
 out('','===== CORRECTION / SELF-REPAIR STATUS =====');
 for(const c of review.repairEvidence)out(JSON.stringify(c));
 if(!review.repairEvidence.length)out('(No candidate detected in the tested turns.)');
 out('  No autonomous corrections were applied. A successful injected-fault alarm is a detection test, not an actual repair.');
 out('ORACLE REPAIR CONTROL (only when a test-only fault is injected; not model-driven):');
 for(const plan of review.oracleRepairControls)out(JSON.stringify(plan));
 if(!review.oracleRepairControls.length)out('(None. No synthetic fault was injected.)');
 out('','===== FINAL MEMORY STATE =====');
 for(const topic of result.finalState.topics){
  const groups=new Map();for(const event of topic.events){if(!groups.has(event.difficulty_id))groups.set(event.difficulty_id,[]);groups.get(event.difficulty_id).push(event);}
  out(`${topic.topic_label} : ${groups.size} identities, ${topic.events.length} observations`);
  for(const [id,events] of groups)out(`  ${id} (${events.length} observations) — ${trim(events.at(-1).root_problem)}`);
 }
 out('','===== REPRODUCIBILITY / SAFETY =====',...review.limitations.map(x=>'- '+x),`Model-cost ledger: ${JSON.stringify(result.cost)}`,'No database writers, no SQL, no deployment and no production state mutation.');
 return lines.join('\n')+'\n';
}
export async function executeJourney(config,{seed=loadJourneySeed(),silent=false}={}){
 const r=await runSimulation(config,{seed,silent});
 const review=analyzeJourney(r);
 return {result:r,review};
}
export function saveJourney(report,review){
 const dir=writeReport(report);
 fs.writeFileSync(path.join(dir,'LONGITUDINAL_REVIEW.txt'),formatReview(report,review),{flag:'wx',mode:0o600});
 fs.writeFileSync(path.join(dir,'longitudinal-review.json'),JSON.stringify(review,null,2)+'\n',{flag:'wx',mode:0o600});
 return dir;
}
async function main(){
 const f=parseJourneyArgs(process.argv.slice(2));
 if(f.help){console.log('S1.6B: --mode offline|model [--limit 1..8] [--inject-fault (offline only)] [--model gpt-4.1-mini|gpt-4o-mini]. Real mode: --allow-spend --budget-usd 0.03..0.50; max 6 turns and at most 18 intended A/B/C calls. Run guarded Next localhost:3001 and MiniLM localhost:8001 first. All memory writes are local simulation only.');return;}
 if(digest(path.join(HERE,'s16-space-sim.mjs'))!==S16A_HASH)throw Error('S1.6A engine checksum drift; no run');
 const current=JSON.parse(fs.readFileSync(path.join(ROOT,'scripts/sandbox/current-local-release.json'),'utf8'));
 if(current.release!=='v37d2c7a3s12'||!fs.existsSync(path.join(ROOT,'scripts/sandbox/v37d2c7a3s16/installation.json')))throw Error('S1.6A installation not verified');
 console.log(`S1.6B longitudinal journey | mode=${f.mode} | turns=${f.limit} | LIVE DB WRITES=0`);
 if(f.mode==='model')console.log(`EXPLICIT PAID OPT-IN: ${f.model} | up to ${f.limit*3} planned A/B/C calls, budget admission USD ${f.budget}, NOT a provider billing cap`);
 const {result,review}=await executeJourney(f);
 const dir=saveJourney(result,review);
 console.log('NOTEPAD REPORT: '+path.join(dir,'LONGITUDINAL_REVIEW.txt'));
 console.log('MODEL TRACE: '+path.join(dir,'trace.json'));
 console.log('MEMORY STATE: '+path.join(dir,'final-state.json'));
 console.log('EVALUATION JSON: '+path.join(dir,'longitudinal-review.json'));
 console.log('SUMMARY: '+JSON.stringify(review.summary));
 console.log('COST: '+JSON.stringify(result.cost));
 if(result.errors?.length)process.exitCode=2;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))main().catch(e=>{console.error('S1.6B REFUSED: '+trim(e?.message??e));process.exitCode=1;});
