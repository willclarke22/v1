#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {flags,runSimulation} from './s16-space-sim.mjs';
const here=path.dirname(fileURLToPath(import.meta.url));
const seed=JSON.parse(fs.readFileSync(path.join(here,'s16-seed.json'),'utf8'));
assert.equal(seed.topics.length,12);
assert.equal(seed.turns.length,18);
const config=flags(['--mode','offline','--limit','18','--inject-fault']);
assert.throws(()=>flags(['--mode','model','--limit','2']),/allow-spend/);
assert.throws(()=>flags(['--mode','offline','--allow-spend']),/forbids/);
assert.throws(()=>flags(['--mode','model','--allow-spend','--budget-usd','0.2','--limit','7']),/limit/);
assert.throws(()=>flags(['--mode','model','--allow-spend','--budget-usd','0.2','--limit','1','--inject-fault']),/offline/);
const startEvents=seed.topics.reduce((n,t)=>n+t.events.length,0);
const result=await runSimulation(config,{seed,silent:true});
assert.equal(result.turns.length,18);
assert.equal(result.before.eventCount,startEvents);
assert.ok(result.after.eventCount>startEvents,'Expected isolated memory evolution');
assert.equal(result.before.topicCount,result.after.topicCount);
assert.ok(result.turns.every(t=>t.teaching?.source==='OFFLINE_STUB_NOT_TEACHING_EVIDENCE'));
assert.ok(result.turns.every(t=>t.assessmentOrigin==='OFFLINE_SCRIPTED'));
assert.ok(result.turns.some(t=>t.action.kind==='reuse'));
assert.ok(result.turns.some(t=>t.action.kind==='create_distinct'),'Scripted offline creation path was not exercised');
assert.ok(result.turns.some(t=>t.action.kind==='refine'),'Scripted offline refinement path was not exercised');
assert.ok(result.relationships.length>=2,'Expected evidence-linked relationship hypotheses');
assert.ok(result.corrections.length>=1,'Expected contradiction-triggered repair candidate');
assert.ok(result.corrections.every(p=>p.automatic_repair_applied===false));
assert.ok(result.audit.some(a=>a.kind==='EXPLICIT_SYNTHETIC_FAULT_INJECTION'));
assert.equal(result.cost.attemptedCalls,0);
assert.equal(result.safeguards.databaseWrites,0);
assert.equal(result.safeguards.cloudWrites,0);
assert.notDeepEqual(result.finalState.topics,seed.topics);
assert.deepEqual(seed.topics[0].events.map(e=>e.origin),['synthetic_seed','synthetic_seed','synthetic_seed'],'Seed input must remain unmutated');
const again=await runSimulation(config,{seed,silent:true});
assert.deepEqual(result.finalState.topics,again.finalState.topics,'Offline state evolution must be deterministic');
assert.ok(result.turns.find(t=>t.turnId==='T10').corrections.length>0);
assert.equal(result.turns.find(t=>t.turnId==='T18').corrections.length,0,'Generic rather-than wording must not imply correction');
console.log('S1.6A SELFTEST PASS: 12 synthetic topics, 18 turns, isolated state evolution, teacher stub tagged, relationship hypotheses, correction proposals, explicit injected error, no provider calls or DB writes.');
