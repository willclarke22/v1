#!/usr/bin/env node
/** No network, provider credentials, Supabase, Git, or database access. */
import assert from 'node:assert/strict';
import {loadJourneySeed,parseJourneyArgs,executeJourney,formatReview} from './s16b-journey.mjs';
const seed=loadJourneySeed();
assert.equal(seed.topics.length,12);
assert.deepEqual(seed.turns.map(t=>t.turn_id),['T01','T07','T10','T02','T06','T08','T15','T11']);
assert.throws(()=>parseJourneyArgs(['--mode','model','--limit','3']),/allow-spend/);
assert.throws(()=>parseJourneyArgs(['--mode','model','--limit','7','--allow-spend','--budget-usd','0.2']),/limit/);
assert.throws(()=>parseJourneyArgs(['--mode','model','--limit','3','--allow-spend','--budget-usd','0.2','--inject-fault']),/offline/);
assert.throws(()=>parseJourneyArgs(['--mode','offline','--limit','9']),/journey has only/);
assert.equal(parseJourneyArgs(['--mode','offline']).limit,8);
assert.equal(parseJourneyArgs(['--mode','model','--allow-spend','--budget-usd','0.10']).limit,3);
assert.ok(seed.turns.every(t=>t.expected));
const flags=parseJourneyArgs(['--mode','offline','--limit','8','--inject-fault']);
const originalJSON=JSON.stringify(seed);
const {result,review}=await executeJourney(flags,{seed,silent:true});
assert.equal(result.turns.length,8);
assert.equal(result.mode,'offline');
assert.equal(review.summary.modelCalls,0);
assert.equal(review.summary.teacherResponsesFromModel,0);
assert.equal(result.safeguards.databaseWrites,0);
assert.equal(result.safeguards.cloudWrites,0);
assert.equal(JSON.stringify(seed),originalJSON);
assert.equal(review.summary.injectedFaultControls,1,'injection should exercise T07');
assert.ok(review.oracleRepairControls[0]);
assert.equal(review.oracleRepairControls[0].oracleRestorationPlan?.applied,false);
assert.ok(review.summary.repairCandidates>=1,'explicit learner denial should trigger a review candidate');
assert.ok(review.summary.relationshipHypotheses>=2,'cross-topic learner comparisons should be observed');
assert.ok(result.turns.every(t=>t.assessmentOrigin==='OFFLINE_SCRIPTED'));
assert.ok(result.turns.every(t=>t.teaching?.source==='OFFLINE_STUB_NOT_TEACHING_EVIDENCE'));
const report=formatReview(result,review);
assert.ok(report.includes('MODEL B — LEARNER-FACING TEACHING'));
assert.ok(report.includes('ORACLE REPAIR CONTROL'));
assert.ok(report.includes('SEMANTIC CROSS-TOPIC RIVALS'));
assert.ok(report.includes('OFFLINE ONLY:'));
assert.ok(report.includes('===== FINAL MEMORY STATE ====='));
const pair=await executeJourney(parseJourneyArgs(['--mode','offline','--limit','3']),{seed,silent:true});
assert.equal(pair.result.turns.length,3);
assert.equal(pair.review.summary.injectedFaultControls,0);
assert.equal(pair.review.summary.modelCalls,0);
console.log('S1.6B SELFTEST PASS: chronological same-learner seed; teacher-review transcript; local state evolution; explicit-fault alarm and un-applied oracle restoration; relation hypotheses; no paid inference or DB writes.');
