export const COMPACT_TEACHING_FORMAT="myway_learning_space_teaching_v1" as const;
export type CompactTeachingInput={topic:string;root_problem:string;evidence_quote:string;original_statement:string;clarification_answer:string};
export type CompactTeachingOutput={teaching_strategy:string;next_step:string;visual_intent:string};
export const COMPACT_TEACH_SCHEMA={type:"object",additionalProperties:false,
 properties:{teaching_strategy:{type:"string"},next_step:{type:"string"},visual_intent:{type:"string"}},
 required:["teaching_strategy","next_step","visual_intent"]} as const;
export const COMPACT_TEACH_SYSTEM_PROMPT=`You are MyWay's concise educational explainer. Reply as strict JSON in the supplied schema.
teaching_strategy: 1-3 clear, accurate sentences SPEAKING DIRECTLY TO THE LEARNER. Answer the specific question using the original statement and clarification. Start with the explanation, not an echo of the question. Don't say "Explain that", "Tell the learner", or praise automatically. Correct unsupported generalizations and acknowledge meaningful uncertainty. Never assume the learner holds a stronger belief than their exact words support.
next_step: ONE short, specific EDUCATIONAL next step (a conceptual comparison, quick example, or an optional understanding check), not workout, treatment or real-world training instructions unless expressly requested. This is internal metadata, not part of the chat response.
visual_intent: describe ONE useful visual that would illuminate the specific mechanism. This is internal Director metadata, not an asset request. Avoid unnecessary visuals when the concept doesn't need one.
Use no invented interests, learner identity, mastery claims, topic relationships or evidence. Never treat a prior MyWay clarification question as learner evidence. Keep all three fields concise.`;
export function compactTeachingInput(input:CompactTeachingInput):CompactTeachingInput {
 const clean=(value:string,max:number)=>value.trim().slice(0,max);
 return {topic:clean(input.topic,110),root_problem:clean(input.root_problem,500),
  evidence_quote:clean(input.evidence_quote,450),original_statement:clean(input.original_statement,2500),
  clarification_answer:clean(input.clarification_answer,2500)};
}
export function validCompactTeachingInput(value:unknown):value is CompactTeachingInput {
 if(!value||typeof value!=="object"||Array.isArray(value))return false;
 const r=value as Record<string,unknown>;
 if(Object.keys(r).sort().join("|")!==["topic","root_problem","evidence_quote","original_statement","clarification_answer"].sort().join("|"))return false;
 return (["topic","root_problem","evidence_quote","original_statement","clarification_answer"] as const).every(k=>
  typeof r[k]==="string"&&r[k].length<={topic:110,root_problem:500,evidence_quote:450,original_statement:2500,clarification_answer:2500}[k])&&
  !!(r.topic as string).trim()&&!!(r.root_problem as string).trim()&&!!(r.original_statement as string).trim();
}
export function validateCompactTeaching(raw:string):{plan?:TeachingPlan;error?:string} {
 let parsed:unknown;try{parsed=parseModelJson(raw);}catch{return {error:"Compact teaching model returned invalid JSON."};}
 if(!parsed||typeof parsed!=="object"||Array.isArray(parsed))return {error:"Teaching output must be an object."};
 const r=parsed as Record<string,unknown>;
 if(Object.keys(r).sort().join("|")!==["teaching_strategy","next_step","visual_intent"].sort().join("|"))
  return {error:"Compact teaching output must contain exactly three fields."};
 for(const key of ["teaching_strategy","next_step","visual_intent"] as const){
  if(typeof r[key]!=="string"||!r[key].trim()||r[key].length>620)return {error:`Invalid compact teaching field: ${key}`};
 }
 // Legacy TeachingPlan and frozen visual handoff retain their exact schema; values that
 // have no learner-provided source are NOT generated by the model.
 return {plan:{learner_reflection:"",teaching_strategy:r.teaching_strategy as string,
  next_step:r.next_step as string,visual_intent:r.visual_intent as string,
  use_interest:"do_not_use",chosen_interest:"",reason:"No learner interests were provided."}};
}
